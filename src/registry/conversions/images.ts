/** The metadata-removal entry targets the source's own format. */
export function resolveTarget(def: ConversionDef, input: DetectedFile): string {
  if (def.id === 'image-strip-metadata') return input.formatId === 'jpeg' ? 'jpeg' : 'png'
  return def.to
}

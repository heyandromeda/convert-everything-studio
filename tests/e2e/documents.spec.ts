test('batch: images → one PDF, merge PDFs, and "convert all images to"', async ({ page }) => {
  await addFiles(page, ['alpha.png', 'photo.jpg', 'text.pdf', 'scanned.pdf'])
  await page.getByRole('button', { name: 'JPEG', exact: true }).click()
  await expect(page.getByTestId('file-card').nth(0).getByTestId('format-picker')).toContainText('JPEG')
  await expect(page.getByTestId('file-card').nth(2).getByTestId('format-picker')).not.toContainText('JPEG')
  await page.getByRole('button', { name: '2 images → one PDF' }).click()
  await page.getByRole('button', { name: 'Merge 2 PDFs' }).click()
  await expect(page.getByTestId('file-card')).toHaveCount(6)
  await convertAndWait(page, 6)
  const combined = await download(page, 4)
  expect(combined.name).toMatch(/^images-.*\.pdf$/)
  expect(pdfPages(combined.path)).toBe(2)
  const merged = await download(page, 5)
  expect(pdfPages(merged.path)).toBe(4)
  expect(pdfText(merged.path)).toContain('page 3')
})


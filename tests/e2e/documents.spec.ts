import { execFileSync } from 'node:child_process'
import * as XLSX from 'xlsx'
import { expect, test, addFiles, ascii, chooseTarget, convertAndWait, download } from './helpers'

const pdfText = (file: string) => execFileSync('pdftotext', ['-layout', file, '-'], { encoding: 'utf8' })
const pdfPages = (file: string) => Number(/Pages:\s+(\d+)/.exec(execFileSync('pdfinfo', [file], { encoding: 'utf8' }))![1])

test.beforeEach(async ({ page }) => {
  await page.goto('/')
})

test('Markdown → HTML is sanitised and keeps structure', async ({ page }) => {
  await addFiles(page, ['notes.md'])
  await chooseTarget(page, 0, 'md-to-html')
  await convertAndWait(page)
  const out = (await download(page, 0)).bytes.toString('utf8')
  expect(out).toContain('<h1>Release Notes</h1>')
  expect(out).toContain('<table>')
  expect(out).toContain('<li>New WebP encoder')
  expect(out).not.toContain('<script>alert')
  expect(out).toContain('Ελληνικά')
})

test('Markdown → PDF and HTML → PDF produce real text PDFs', async ({ page }) => {
  await addFiles(page, ['notes.md', 'page.html', 'plain.txt'])
  await chooseTarget(page, 0, 'md-to-pdf')
  await chooseTarget(page, 1, 'html-to-pdf')
  await chooseTarget(page, 2, 'txt-to-pdf')
  await convertAndWait(page, 3)
  const md = await download(page, 0)
  expect(ascii(md.bytes, 0, 5)).toBe('%PDF-')
  const mdText = pdfText(md.path)
  expect(mdText).toContain('Release Notes')
  expect(mdText).toContain('Safer archive extraction')
  expect(mdText).toContain('Café')
  const html = pdfText((await download(page, 1)).path)
  expect(html).toContain('Welcome')
  expect(html).toContain('Apples')
  const txt = pdfText((await download(page, 2)).path)
  expect(txt).toContain('café résumé')
})

test('HTML → Markdown drops scripts and unsafe links', async ({ page }) => {
  await addFiles(page, ['page.html'])
  await chooseTarget(page, 0, 'html-to-md')
  await convertAndWait(page)
  const md = (await download(page, 0)).bytes.toString('utf8')
  expect(md).toContain('# Welcome')
  expect(md).toContain('[a good link](https://example.com)')
  expect(md).not.toContain('javascript:')
  expect(md).not.toContain('tracker.example.com')
  expect(md).toMatch(/\|\s*Name\s*\|\s*Qty\s*\|/)
})

test('PDF → text, PDF → PNG pages, page extraction', async ({ page }) => {
  await addFiles(page, ['text.pdf', 'text.pdf', 'text.pdf'])
  await expect(page.getByTestId('file-card').first()).toContainText('3 pages')
  await chooseTarget(page, 0, 'pdf-to-txt')
  await chooseTarget(page, 1, 'pdf-to-png')
  await chooseTarget(page, 2, 'pdf-extract-pages')
  const third = page.getByTestId('file-card').nth(2)
  await third.getByLabel('Conversion settings').click()
  await third.getByLabel('Pages').fill('2-3')
  await convertAndWait(page, 3)
  const text = (await download(page, 0)).bytes.toString('utf8')
  expect(text).toContain('--- Page 2 ---')
  expect(text).toContain('selectable text on page 3')
  await expect(page.getByTestId('file-card').nth(1).getByTestId('result-row')).toHaveCount(3)
  const png = await download(page, 1, 1)
  expect(png.name).toBe('text-page-2.png')
  expect(ascii(png.bytes, 1, 3)).toBe('PNG')
  const sub = await download(page, 2)
  expect(pdfPages(sub.path)).toBe(2)
  expect(pdfText(sub.path)).toContain('page 2')
})


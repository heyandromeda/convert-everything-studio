test('spreadsheets: CSV → XLSX keeps leading zeros; XLSX → CSV (all sheets) neutralises formulas', async ({ page }) => {
  await addFiles(page, ['people.csv', 'book.xlsx'])
  await expect(page.getByTestId('file-card').nth(1)).toContainText('2 sheets')
  await chooseTarget(page, 0, 'sheet-to-xlsx')
  await chooseTarget(page, 1, 'sheet-to-csv')
  const second = page.getByTestId('file-card').nth(1)
  await second.getByLabel('Conversion settings').click()
  await second.getByLabel('Worksheet').click()
  await page.getByRole('option', { name: 'All sheets (one file each)' }).click()
  await convertAndWait(page, 2)
  const xlsx = await download(page, 0)
  const wb = XLSX.read(xlsx.bytes)
  const rows = XLSX.utils.sheet_to_json<unknown[]>(wb.Sheets[wb.SheetNames[0]], { header: 1, raw: true })
  expect(rows[1]).toEqual(['Smith, John', '02134', 12.5, 'multi\nline'])
  expect(rows[2][2]).toBe(-3)
  await expect(second.getByTestId('result-row')).toHaveCount(2)
  const sales = (await download(page, 1, 0)).bytes.toString('utf8')
  // openpyxl saves formulas without cached results; we must not invent them.
  expect(sales).toContain('Widget,10,2.5,,00123')
  await expect(second).toContainText('no saved result')
  const notes = await download(page, 1, 1)
  expect(notes.name).toBe('book-Notes.csv')
  expect(notes.bytes.toString('utf8')).toContain("'=cmd|calc")
  expect(notes.bytes.toString('utf8')).toContain('"Line one\nLine two"')
})

test('JSON ↔ CSV/YAML/XML and subtitles', async ({ page }) => {
  await addFiles(page, ['records.json', 'config.yaml', 'library.xml', 'captions.srt'])
  await chooseTarget(page, 0, 'sheet-to-csv')
  await chooseTarget(page, 1, 'data-to-json')
  await chooseTarget(page, 2, 'data-to-json')
  await chooseTarget(page, 3, 'subs-to-vtt')
  await convertAndWait(page, 4)
  const csv = (await download(page, 0)).bytes.toString('utf8')
  expect(csv.split('\r\n')[0]).toBe('id,name,tags,active')
  expect(csv).toContain('"[""x"",""y""]"')
  expect(JSON.parse((await download(page, 1)).bytes.toString('utf8'))).toEqual({ server: { host: 'localhost', ports: [80, 443] }, enabled: true })
  const xml = JSON.parse((await download(page, 2)).bytes.toString('utf8'))
  expect(xml.library.book[1].title).toBe('Emma')
  const vtt = (await download(page, 3)).bytes.toString('utf8')
  expect(vtt.startsWith('WEBVTT')).toBe(true)
  expect(vtt).toContain('00:00:01.000 --> 00:00:03.500')
})

